#!/usr/bin/env node
// Scans plugins/*/client/index.ts and generates plugins/index.ts automatically.
// Run before esbuild — never edit plugins/index.ts manually.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pluginsDir = path.resolve(__dirname, "../../../../plugins");
const outputFile = path.join(pluginsDir, "index.ts");

const toPascalCase = (name) => name.charAt(0).toUpperCase() + name.slice(1);

const plugins = fs
  .readdirSync(pluginsDir)
  .filter((name) => {
    const stat = fs.statSync(path.join(pluginsDir, name));
    if (!stat.isDirectory()) return false;
    return fs.existsSync(path.join(pluginsDir, name, "client", "index.ts"));
  })
  .sort();

const lines = [
  "// Auto-generated by scripts/gen-plugins-index.mjs — do not edit manually.",
  ...plugins.map((name) => `import { register${toPascalCase(name)} } from './${name}/client/index';`),
  "",
  "export function registerAllPlugins(): void {",
  ...plugins.map((name) => `  register${toPascalCase(name)}();`),
  "}",
  "",
];

fs.writeFileSync(outputFile, lines.join("\n"));
console.log(`[plugins] Generated index.ts — ${plugins.length} plugin(s): ${plugins.join(", ") || "(none)"}`);

const pad = (n) => String(n).padStart(2, "0");
const d = new Date();
const ts = `${d.getUTCFullYear()}${pad(d.getUTCMonth() + 1)}${pad(d.getUTCDate())}-${pad(d.getUTCHours())}.${pad(d.getUTCMinutes())}.${pad(d.getUTCSeconds())}`;
const buildConfigFile = path.join(__dirname, "..", "buildConfig.ts");
const existing = fs.existsSync(buildConfigFile) ? fs.readFileSync(buildConfigFile, "utf8") : "";
const existingTs = existing.match(/"([^"]+)"/)?.[1] ?? "";
if (existingTs.slice(0, 14) !== ts.slice(0, 14)) {
  fs.writeFileSync(buildConfigFile, `// Auto-generated — do not edit\nexport const MC_BUILD_TIMESTAMP = "${ts}";\n`);
  console.log(`[build] mc_bindings timestamp: ${ts}`);
}
